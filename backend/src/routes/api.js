const {createStaffProfileService}=require('../services/staffProfile');
const {createStaffService}=require('../services/staff');
const {createAlertService}=require('../services/alerts');
const {createTaskService}=require('../services/tasks');
const {registerDevice}=require('../services/devices');
const {createUnitService}=require('../services/units');
const express=require('express');
const {createResidentService}=require('../services/residents');
const {readDashboard}=require('../services/dashboard');
function createRoutes(db,env){
 const properties=require('../services/properties').createPropertyService(db);
 const billing=require('../services/billing').createBillingService(db,env);
 const incidents=require('../services/incidents').createIncidentService(db,env);
 const configuration=require('../services/configuration').createConfigurationService(db);
 const router=express.Router(), residents=createResidentService(db,env), tasks=createTaskService(db), alerts=createAlertService(db);
 router.get('/configuration',async(req,res)=>{const actor=await db.authenticate(req.headers.authorization?.match(/^Bearer (.+)$/i)?.[1],['system_admin','property_staff','elderly','family']);res.json(await configuration.read(actor));});
 router.get('/mobile/properties',async(req,res)=>{const actor=await db.authenticate(req.headers.authorization?.match(/^Bearer (.+)$/i)?.[1],['elderly','family']);res.json(await properties.linked(actor));});
 router.get('/mobile/incidents',async(req,res)=>{const actor=await db.authenticate(req.headers.authorization?.match(/^Bearer (.+)$/i)?.[1],['elderly','family']);res.json(await incidents.mobile(actor));});
 router.get('/mobile/subscription',async(req,res)=>{const actor=await db.authenticate(req.headers.authorization?.match(/^Bearer (.+)$/i)?.[1],['elderly','family']);res.json(await billing.mobile(actor));});
 router.get('/mobile/alerts',async(req,res)=>{const actor=await db.authenticate(req.headers.authorization?.match(/^Bearer (.+)$/i)?.[1],['elderly','family']);res.json(await alerts.mobile(actor));});
 router.post('/mobile/alerts/sos',async(req,res)=>{const actor=await db.authenticate(req.headers.authorization?.match(/^Bearer (.+)$/i)?.[1],['elderly']);const result=await alerts.create(actor,req.body,true);res.status(result.replayed?200:201).json(result);});
 router.get('/mobile/tasks',async(req,res)=>{
  const actor=await db.authenticate(req.headers.authorization?.match(/^Bearer (.+)$/i)?.[1],['elderly','family']);
  res.json(await tasks.mobile(actor));
 });
 router.post('/mobile/device',async(req,res)=>{
  const actor=await db.authenticate(req.headers.authorization?.match(/^Bearer (.+)$/i)?.[1],['elderly']);
  res.json(await registerDevice(db,actor,req.body));
 });
 router.use(async(req,res,next)=>{req.actor=await db.authenticate(req.headers.authorization?.match(/^Bearer (.+)$/i)?.[1]);next();});
 router.get('/dashboard',async(req,res)=>res.json(await readDashboard(db,req.actor)));
 router.use('/alerts',(req,res,next)=>req.actor.role==='property_staff'?next():res.status(403).json({error:'Property staff account required.'}));
 router.get('/alerts',async(req,res)=>res.json(await alerts.list(req.actor)));
 router.get('/alerts/options',async(req,res)=>res.json(await alerts.options(req.actor)));
 router.post('/alerts',async(req,res)=>{const result=await alerts.create(req.actor,req.body);res.status(result.replayed?200:201).json(result);});
 router.patch('/alerts/:id',async(req,res)=>res.json(await alerts.update(req.actor,req.params.id,req.body)));
 router.use('/residents',(req,res,next)=>req.actor.role==='property_staff'?next():res.status(403).json({error:'Property staff account required.'}));
 router.get('/residents',async(req,res)=>res.json(await residents.list(req.actor)));
 router.post('/residents',async(req,res)=>res.status(201).json(await residents.invite(req.actor,req.body)));
 router.patch('/residents/:id',async(req,res)=>res.json({id:await residents.save(req.actor,req.params.id,req.body)}));
 const units=createUnitService(db);
 router.use('/units',(req,res,next)=>req.actor.role==='property_staff'?next():res.status(403).json({error:'Property staff account required.'}));
 router.get('/units',async(req,res)=>res.json(await units.list(req.actor)));
 router.post('/units',async(req,res)=>{const result=await units.create(req.actor,req.body);res.status(result.created?201:200).json(result);});
 router.use('/tasks',(req,res,next)=>req.actor.role==='property_staff'?next():res.status(403).json({error:'Property staff account required.'}));
 router.get('/tasks',async(req,res)=>res.json(await tasks.list(req.actor)));
 router.post('/tasks',async(req,res)=>{const result=await tasks.create(req.actor,req.body);res.status(result.replayed?200:201).json(result);});
 router.patch('/tasks/:id',async(req,res)=>res.json(await tasks.update(req.actor,req.params.id,req.body)));
 const staff=createStaffService(db,env);
 router.use('/staff',(req,res,next)=>req.actor.role==='property_staff'?next():res.status(403).json({error:'Property staff account required.'}));
 const profile=createStaffProfileService(db);
 router.get('/staff/profile',async(req,res)=>res.json(await profile.read(req.actor)));
 router.patch('/staff/profile',async(req,res)=>res.json(await profile.update(req.actor,req.body)));
 router.get('/staff/options',async(req,res)=>res.json(await staff.options(req.actor)));
 router.get('/staff',async(req,res)=>res.json(await staff.snapshot(req.actor,req.query)));
 router.post('/staff/commands',async(req,res)=>res.json(await staff.command(req.actor,req.body)));
 router.post('/staff/invitations',async(req,res)=>res.status(201).json(await staff.invite(req.actor,req.body)));
 router.get('/billing',async(req,res)=>res.json(await billing.read(req.actor)));
 router.post('/billing/checkout',async(req,res)=>res.json(await billing.checkout(req.actor,req.body)));
 router.post('/billing/portal',async(req,res)=>res.json(await billing.portal(req.actor,req.body)));
 router.post('/billing/sync',async(req,res)=>res.json(await billing.sync(req.actor,req.body)));
 const notifications=require('../services/notifications').createNotificationService(db);
 router.get('/notifications',async(req,res)=>res.json(await notifications.list(req.actor,req.query)));
 router.post('/notifications/:id/read',async(req,res)=>res.json(await notifications.read(req.actor,req.params.id)));
 router.use('/incidents',(req,res,next)=>req.actor.role==='property_staff'?next():res.status(403).json({error:'Property staff account required.'}));
 router.get('/incidents/options',async(req,res)=>res.json(await incidents.options(req.actor)));
 router.get('/incidents',async(req,res)=>res.json(await incidents.list(req.actor)));
 router.post('/incidents/commands',async(req,res)=>res.json(await incidents.command(req.actor,req.body)));
 router.post('/incidents/:id/evidence/:fileId',express.raw({type:'application/octet-stream',limit:'10mb'}),async(req,res)=>res.json(await incidents.upload(req.actor,req.params.id,req.params.fileId,req.query.filename,req.body)));
 router.get('/incidents/:id/evidence/:fileId',async(req,res)=>res.json(await incidents.download(req.actor,req.params.id,req.params.fileId)));
 const reports=require('../services/reports').createReportService(db);
 router.get('/reports/options',async(req,res)=>res.json(await reports.options(req.actor)));
 router.get('/reports',async(req,res)=>res.json(await reports.read(req.actor,req.query)));
 const photo=require('../services/staffPhoto').createStaffPhotoService(db,env);
 router.get('/staff/profile/photo',async(req,res)=>{res.set('Cache-Control','no-store');res.json(await photo.read(req.actor));});
 router.put('/staff/profile/photo',express.raw({type:'application/octet-stream',limit:'2mb'}),async(req,res)=>res.json(await photo.upload(req.actor,req.query.expected,req.body)));
 router.delete('/staff/profile/photo',async(req,res)=>res.json(await photo.remove(req.actor,req.query.expected)));
 router.put('/admin/configuration',async(req,res)=>res.json(await configuration.save(req.actor,req.body)));
 router.get('/admin/properties',async(req,res)=>res.json(await properties.list(req.actor)));
 router.post('/admin/properties/commands',async(req,res)=>res.json(await properties.command(req.actor,req.body)));
 router.get('/staff/properties',async(req,res)=>res.json(await properties.linked(req.actor)));
 const users=require('../services/users').createUserService(db,env);
 router.get('/admin/users',async(req,res)=>res.json(await users.list(req.actor)));
 router.post('/admin/users/invitations',async(req,res)=>res.status(201).json(await users.invite(req.actor,req.body)));
 router.patch('/admin/users/:id',async(req,res)=>res.json({id:await users.update(req.actor,req.params.id,req.body)}));
 router.post('/admin/users/:id/links',async(req,res)=>{await users.link(req.actor,req.params.id,req.body);res.json({saved:true});});
 router.post('/admin/users/:id/recovery',async(req,res)=>res.json(await users.recover(req.actor,req.params.id)));
 const adminBilling=require('../services/adminBilling').createAdminBillingService(db,env);
 router.get('/admin/billing',async(req,res)=>res.json(await adminBilling.read(req.actor)));
 router.post('/admin/billing/commands',async(req,res)=>res.json(await adminBilling.command(req.actor,req.body)));
 router.post('/admin/billing/refunds',async(req,res)=>res.json(await adminBilling.refund(req.actor,req.body)));
 const analytics=require('../services/analytics').createAnalyticsService(db);
 router.get('/admin/analytics',async(req,res)=>res.json(await analytics.read(req.actor,req.query)));
 const audit=require('../services/audit').createAuditService(db);
 router.get('/admin/audit',async(req,res)=>res.json(await audit.read(req.actor,req.query)));
 const adminDashboard=require('../services/adminDashboard').createAdminDashboardService(db);
 router.get('/admin/dashboard',async(req,res)=>res.json(await adminDashboard.read(req.actor,req.query)));
 const adminProfile=require('../services/adminProfile').createAdminProfileService(db);
 router.get('/admin/profile',async(req,res)=>res.json(await adminProfile.read(req.actor)));
 router.patch('/admin/profile',async(req,res)=>res.json(await adminProfile.update(req.actor,req.body)));
 const adminPhoto=require('../services/adminPhoto').createAdminPhotoService(db,env);
 router.get('/admin/profile/photo',async(req,res)=>res.json(await adminPhoto.read(req.actor)));
 router.put('/admin/profile/photo',express.raw({type:'application/octet-stream',limit:'2mb'}),async(req,res)=>res.json(await adminPhoto.upload(req.actor,req.query.expected,req.body)));
 router.delete('/admin/profile/photo',async(req,res)=>res.json(await adminPhoto.remove(req.actor,req.query.expected)));
 const preferences=require('../services/adminPreferences').createAdminPreferencesService(db);
 router.get('/admin/preferences',async(req,res)=>res.json(await preferences.read(req.actor)));
 router.put('/admin/preferences',async(req,res)=>res.json(await preferences.save(req.actor,req.body)));
 const adminNotifications=require('../services/adminNotifications').createAdminNotificationService(db);
 router.get('/admin/notifications',async(req,res)=>res.json(await adminNotifications.list(req.actor,req.query)));
 router.post('/admin/notifications/:id/read',async(req,res)=>res.json(await adminNotifications.read(req.actor,req.params.id)));
 return router;
}
module.exports={createRoutes};



